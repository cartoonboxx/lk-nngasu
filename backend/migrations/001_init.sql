-- Схема university_cabinet (PostgreSQL) по DBML-описанию проекта.
--
-- Отличия от DBML (всё осознанно и перечислено здесь):
--   * email хранится в нижнем регистре (CHECK app_user_email_lowercase) — вход идёт по email;
--   * максимум один текущий семестр (частичный уникальный индекс semester_single_current_idx);
--   * ON DELETE CASCADE там, где дочерняя запись не живёт без родителя:
--     material → topic, assignment_file / submission → assignment, submission_file → submission;
--   * ON DELETE SET NULL для аватара (app_user.avatar_file_id);
--   * именованный FK assignment_topic_course_fk — по имени API отдаёт понятную ошибку.

CREATE TYPE lesson_kind      AS ENUM ('lecture', 'practice', 'laboratory', 'consultation', 'exam');
CREATE TYPE submission_state AS ENUM ('not_submitted', 'submitted', 'reviewed');

-- ====================================================
-- БЛОК 1. Файлы, пользователи и структура вуза
-- ====================================================

-- storage_key = "<user_id>/<random>/<имя файла>" — путь в папке пользователя.
-- По нему определяются владелец и имя файла (см. internal/platform/filekey).
CREATE TABLE file (
    id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_key text NOT NULL UNIQUE
);

CREATE TABLE app_user (
    id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name      varchar(50)  NOT NULL,
    first_name     varchar(50)  NOT NULL,
    middle_names   varchar(50),
    email          varchar(255) NOT NULL UNIQUE
                   CONSTRAINT app_user_email_lowercase CHECK (email = lower(email)),
    password_hash  varchar(255) NOT NULL,
    avatar_file_id int REFERENCES file (id) ON DELETE SET NULL,
    is_admin       bool NOT NULL DEFAULT false,
    is_active      bool NOT NULL DEFAULT true -- soft delete
);

CREATE TABLE department (
    id   int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL UNIQUE
);

CREATE TABLE specialization (
    id   int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(20)  NOT NULL UNIQUE,
    name varchar(200) NOT NULL
);

CREATE TABLE study_group (
    id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(50) NOT NULL,
    specialization_id int         NOT NULL REFERENCES specialization (id),
    admission_year    smallint    NOT NULL
                      CONSTRAINT study_group_admission_year_valid CHECK (admission_year >= 2000),
    UNIQUE (name, admission_year)
);
CREATE INDEX study_group_specialization_idx ON study_group (specialization_id);

CREATE TABLE teacher (
    user_id       int PRIMARY KEY REFERENCES app_user (id),
    department_id int NOT NULL REFERENCES department (id)
);
CREATE INDEX teacher_department_idx ON teacher (department_id);

CREATE TABLE student (
    user_id            int PRIMARY KEY REFERENCES app_user (id),
    group_id           int NOT NULL REFERENCES study_group (id),
    record_book_number varchar(50) UNIQUE,
    is_headman         bool NOT NULL DEFAULT false
);
CREATE INDEX student_group_idx ON student (group_id);

-- ====================================================
-- БЛОК 2. Учебный контекст
-- ====================================================

CREATE TABLE semester (
    id                  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_start smallint NOT NULL,
    number              smallint NOT NULL CONSTRAINT semester_number_valid CHECK (number IN (1, 2)),
    is_current          bool     NOT NULL DEFAULT false,
    UNIQUE (academic_year_start, number)
);
CREATE UNIQUE INDEX semester_single_current_idx ON semester (is_current) WHERE is_current;

CREATE TABLE subject (
    id   int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL UNIQUE
);

-- Курс группы в семестре. Студенты курса = студенты группы.
CREATE TABLE course_offering (
    id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id  int         NOT NULL REFERENCES subject (id),
    group_id    int         NOT NULL REFERENCES study_group (id),
    semester_id int         NOT NULL REFERENCES semester (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (subject_id, group_id, semester_id)
);
CREATE INDEX course_offering_group_semester_idx ON course_offering (group_id, semester_id);
CREATE INDEX course_offering_semester_idx       ON course_offering (semester_id);

CREATE TABLE workload (
    id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id     int         NOT NULL REFERENCES course_offering (id),
    teacher_id    int         NOT NULL REFERENCES teacher (user_id),
    lesson_type   lesson_kind NOT NULL,
    planned_hours numeric(7, 2)
                  CONSTRAINT workload_hours_nonnegative CHECK (planned_hours IS NULL OR planned_hours >= 0),
    UNIQUE (course_id, teacher_id, lesson_type)
);
CREATE INDEX workload_teacher_idx ON workload (teacher_id);

-- ====================================================
-- БЛОК 3. Расписание (двухнедельный шаблон)
-- ====================================================

CREATE TABLE room (
    id     int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number varchar(30) NOT NULL UNIQUE
);

CREATE TABLE lesson (
    id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workload_id int      NOT NULL REFERENCES workload (id),
    week_number smallint NOT NULL CONSTRAINT lesson_week_number_valid CHECK (week_number IN (1, 2)),
    day_of_week smallint NOT NULL CONSTRAINT lesson_day_of_week_valid CHECK (day_of_week BETWEEN 1 AND 6),
    starts_at   time     NOT NULL,
    room_id     int      NOT NULL REFERENCES room (id),
    UNIQUE (workload_id, week_number, day_of_week, starts_at)
);
-- без UNIQUE: потоковые лекции проходят в одной аудитории в одно время
CREATE INDEX lesson_room_slot_idx ON lesson (room_id, week_number, day_of_week, starts_at);
CREATE INDEX lesson_slot_idx      ON lesson (week_number, day_of_week, starts_at);

-- ====================================================
-- БЛОК 4. Темы и материалы
-- ====================================================

CREATE TABLE topic (
    id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   int          NOT NULL REFERENCES course_offering (id),
    title       varchar(200) NOT NULL,
    description text,
    position    int          NOT NULL CONSTRAINT topic_position_positive CHECK (position >= 1),
    UNIQUE (id, course_id)
);
CREATE INDEX topic_course_position_idx ON topic (course_id, position);

CREATE TABLE material (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id     int          NOT NULL REFERENCES topic (id) ON DELETE CASCADE,
    title        varchar(200) NOT NULL,
    file_id      int REFERENCES file (id),
    external_url text,
    position     int          NOT NULL DEFAULT 1 CONSTRAINT material_position_positive CHECK (position >= 1),
    created_by   int          NOT NULL REFERENCES teacher (user_id),
    created_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT material_has_at_least_one_source CHECK (file_id IS NOT NULL OR external_url IS NOT NULL)
);
CREATE INDEX material_topic_position_idx ON material (topic_id, position);
CREATE INDEX material_file_idx           ON material (file_id);

-- ====================================================
-- БЛОК 5. Задания и ответы студентов
-- ====================================================

CREATE TABLE assignment (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id    int          NOT NULL REFERENCES course_offering (id),
    topic_id     int          NOT NULL,
    created_by   int          NOT NULL REFERENCES teacher (user_id),
    title        varchar(200) NOT NULL,
    description  text,
    deadline_at  timestamptz,
    published_at timestamptz  NOT NULL DEFAULT now(),
    -- тема должна принадлежать тому же курсу
    CONSTRAINT assignment_topic_course_fk FOREIGN KEY (topic_id, course_id) REFERENCES topic (id, course_id)
);
CREATE INDEX assignment_course_deadline_idx ON assignment (course_id, deadline_at);
CREATE INDEX assignment_topic_course_idx    ON assignment (topic_id, course_id);

CREATE TABLE assignment_file (
    assignment_id int NOT NULL REFERENCES assignment (id) ON DELETE CASCADE,
    file_id       int NOT NULL REFERENCES file (id),
    PRIMARY KEY (assignment_id, file_id)
);
CREATE INDEX assignment_file_file_idx ON assignment_file (file_id);

-- Один ответ на пару (задание, студент); оценка хранится здесь же.
CREATE TABLE submission (
    id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id int              NOT NULL REFERENCES assignment (id) ON DELETE CASCADE,
    student_id    int              NOT NULL REFERENCES student (user_id),
    status        submission_state NOT NULL DEFAULT 'submitted',
    answer_text   text,
    submitted_at  timestamptz,
    review_comment text,
    reviewed_by   int REFERENCES teacher (user_id),
    reviewed_at   timestamptz,
    grade         numeric(2, 1) -- оценка от 0.0 до 5.0
        CONSTRAINT submission_grade_range_valid CHECK (grade IS NULL OR (grade >= 0.0 AND grade <= 5.0)),
    UNIQUE (assignment_id, student_id),
    CONSTRAINT submission_sent_state_valid CHECK (
        (status = 'not_submitted' AND submitted_at IS NULL)
        OR (status <> 'not_submitted' AND submitted_at IS NOT NULL)),
    CONSTRAINT submission_review_state_valid CHECK (
        (status = 'reviewed' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND grade IS NOT NULL)
        OR (status IN ('not_submitted', 'submitted') AND reviewed_by IS NULL AND reviewed_at IS NULL AND grade IS NULL))
);
CREATE INDEX submission_assignment_status_idx ON submission (assignment_id, status);
CREATE INDEX submission_student_idx           ON submission (student_id);

CREATE TABLE submission_file (
    submission_id int NOT NULL REFERENCES submission (id) ON DELETE CASCADE,
    file_id       int NOT NULL REFERENCES file (id),
    PRIMARY KEY (submission_id, file_id)
);
CREATE INDEX submission_file_file_idx ON submission_file (file_id);
