-- Заявки на регистрацию.
-- Пользователь отправляет заявку (email, пароль, паспорт, СНИЛС, комментарий),
-- администратор одобряет её — тогда создаётся app_user — или отклоняет.

CREATE TYPE registration_status AS ENUM ('pending', 'approved', 'rejected');

CREATE TABLE registration_request (
    id            int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(255) NOT NULL,
    password_hash varchar(255) NOT NULL,        -- bcrypt; при одобрении переносится в app_user
    passport      varchar(10)  NOT NULL,        -- только цифры: серия (4) + номер (6)
    snils         varchar(11)  NOT NULL,        -- только цифры
    comment       text,
    status        registration_status NOT NULL DEFAULT 'pending',
    created_at    timestamptz NOT NULL DEFAULT now(),

    reviewed_by   int REFERENCES app_user (id), -- администратор, который обработал заявку
    reviewed_at   timestamptz,
    reject_reason text,
    user_id       int REFERENCES app_user (id), -- созданный пользователь (если одобрена)

    CONSTRAINT registration_request_passport_digits CHECK (passport ~ '^[0-9]{10}$'),
    CONSTRAINT registration_request_snils_digits    CHECK (snils ~ '^[0-9]{11}$'),
    CONSTRAINT registration_request_reviewed CHECK (
        (status = 'pending'  AND reviewed_at IS NULL     AND user_id IS NULL)
     OR (status = 'approved' AND reviewed_at IS NOT NULL AND user_id IS NOT NULL)
     OR (status = 'rejected' AND reviewed_at IS NOT NULL AND user_id IS NULL)
    )
);

-- Одна необработанная заявка на email: повторная отправка, пока первая ждёт, — 409.
CREATE UNIQUE INDEX registration_request_pending_email
    ON registration_request (email) WHERE status = 'pending';

-- Список заявок в админке: по статусу, новые сверху.
CREATE INDEX registration_request_status_created
    ON registration_request (status, created_at DESC);
