-- Чаты: личные (direct) и групповые (group, по одному на учебную группу).
--
--   * личный чат хранит пару пользователей как (user_low < user_high) — так пара уникальна
--     независимо от того, кто начал переписку;
--   * групповой чат создаётся лениво, участники не хранятся: это студенты группы и преподаватели,
--     ведущие у группы курсы (см. internal/modules/chat);
--   * chat_read — «прочитано до сообщения N» для каждого пользователя (счётчик непрочитанных);
--   * удаление сообщения мягкое (deleted_at, текст стирается), чтобы не ломать ответы и счётчики.

CREATE TYPE chat_kind AS ENUM ('direct', 'group');

CREATE TABLE chat (
                      id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      kind       chat_kind   NOT NULL,
                      group_id   int REFERENCES study_group (id) ON DELETE CASCADE,
                      user_low   int REFERENCES app_user (id),
                      user_high  int REFERENCES app_user (id),
                      created_at timestamptz NOT NULL DEFAULT now(),
                      CONSTRAINT chat_shape_valid CHECK (
                          (kind = 'group'  AND group_id IS NOT NULL AND user_low IS NULL AND user_high IS NULL)
                              OR
                          (kind = 'direct' AND group_id IS NULL AND user_low IS NOT NULL AND user_high IS NOT NULL
                              AND user_low < user_high)
                          )
);
CREATE UNIQUE INDEX chat_group_uidx  ON chat (group_id)            WHERE kind = 'group';
CREATE UNIQUE INDEX chat_direct_uidx ON chat (user_low, user_high) WHERE kind = 'direct';
CREATE INDEX chat_user_high_idx ON chat (user_high) WHERE kind = 'direct';

CREATE TABLE chat_message (
                              id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              chat_id    int         NOT NULL REFERENCES chat (id) ON DELETE CASCADE,
                              sender_id  int         NOT NULL REFERENCES app_user (id),
                              body       text        NOT NULL DEFAULT ''
                                  CONSTRAINT chat_message_body_len CHECK (char_length(body) <= 4000),
                              created_at timestamptz NOT NULL DEFAULT now(),
                              edited_at  timestamptz,
                              deleted_at timestamptz
);
CREATE INDEX chat_message_chat_idx ON chat_message (chat_id, id);

CREATE TABLE chat_message_file (
                                   message_id bigint NOT NULL REFERENCES chat_message (id) ON DELETE CASCADE,
                                   file_id    int    NOT NULL REFERENCES file (id),
                                   PRIMARY KEY (message_id, file_id)
);
CREATE INDEX chat_message_file_file_idx ON chat_message_file (file_id);

CREATE TABLE chat_read (
                           chat_id              int    NOT NULL REFERENCES chat (id) ON DELETE CASCADE,
                           user_id              int    NOT NULL REFERENCES app_user (id),
                           last_read_message_id bigint NOT NULL DEFAULT 0,
                           PRIMARY KEY (chat_id, user_id)
);
CREATE INDEX chat_read_user_idx ON chat_read (user_id);