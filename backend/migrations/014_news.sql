-- Новости: публичная лента и редактор администратора.
-- Заголовка, обложки и закрепления в контракте нет: анонс (excerpt) сервер
-- вычисляет из текста, поэтому в таблице только body.

CREATE TYPE news_status AS ENUM ('draft', 'published', 'archived');

CREATE TABLE news (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id    int         NOT NULL REFERENCES app_user (id),
    body         text        NOT NULL,
    status       news_status NOT NULL DEFAULT 'draft',
    published_at timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT news_body_length_valid CHECK (char_length(body) BETWEEN 1 AND 50000),
    -- дата публикации есть ровно у опубликованных
    CONSTRAINT news_published_at_valid CHECK (
        (status = 'published' AND published_at IS NOT NULL)
        OR (status <> 'published' AND published_at IS NULL))
);

-- Публичная лента: опубликованные, свежие первыми.
CREATE INDEX news_feed_idx ON news (published_at DESC, id DESC) WHERE status = 'published';
CREATE INDEX news_updated_idx ON news (updated_at DESC, id DESC);
CREATE INDEX news_author_idx ON news (author_id);
