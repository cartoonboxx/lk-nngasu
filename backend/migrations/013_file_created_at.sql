-- за 24 часа так и не привязали ни к материалу, заданию, ответу, сообщению, ни к аватару.
-- Уже существующим файлам ставится время миграции: непривязанные из них
-- будут удалены через сутки после обновления.
ALTER TABLE file ADD COLUMN created_at timestamptz NOT NULL DEFAULT now();
