-- Удаление сообщения чата теперь полное (контракт WebSocket: message.delete без tombstone).
-- Сообщения, удалённые раньше мягко (deleted_at), убираются совсем: их текст и вложения
-- уже стёрты, а в истории и последнем сообщении они больше не показываются.
-- Колонка deleted_at остаётся для совместимости, новые записи её не заполняют.

DELETE FROM chat_message WHERE deleted_at IS NOT NULL;
