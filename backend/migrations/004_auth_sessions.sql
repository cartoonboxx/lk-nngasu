-- Авторизация по документации API: согласие с условиями в заявке,
-- refresh-сессии с ротацией токенов, приглашения для активации учётки.

-- 1. Заявка на регистрацию: какую версию условий принял пользователь и когда.
ALTER TABLE registration_request
    ADD COLUMN IF NOT EXISTS terms_version     varchar(32),
    ADD COLUMN IF NOT EXISTS accepted_terms_at timestamptz;

-- 2. Сессия входа. Живёт 1 или 30 суток с момента входа (remember_me) и не продлевается.
--    Access-токен несёт id сессии: отзыв сессии сразу отзывает и её access-токены.
CREATE TABLE auth_session (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id       int         NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    remember_me   boolean     NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    expires_at    timestamptz NOT NULL,
    revoked_at    timestamptz,
    revoke_reason varchar(32)                -- logout | refresh_reused | ...
);

CREATE INDEX auth_session_user_active ON auth_session (user_id) WHERE revoked_at IS NULL;

-- 3. Refresh-токены сессии. Хранится только SHA-256 токена. При каждом refresh
--    текущий токен помечается использованным и выдаётся новый; повторное
--    использование старого = утечка, вся сессия отзывается.
CREATE TABLE auth_refresh_token (
    token_hash bytea       PRIMARY KEY,
    session_id uuid        NOT NULL REFERENCES auth_session (id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    used_at    timestamptz
);

CREATE INDEX auth_refresh_token_session ON auth_refresh_token (session_id);

-- 4. Приглашение задать пароль: администратор создаёт пользователя без пароля,
--    тот получает письмо со ссылкой и задаёт пароль через POST /auth/activate.
--    Хранится только SHA-256 токена; срок — 24 часа; новое приглашение отменяет прежние.
CREATE TABLE user_invitation (
    id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    int         NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    token_hash bytea       NOT NULL UNIQUE,
    created_by int         REFERENCES app_user (id),
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    used_at    timestamptz,
    revoked_at timestamptz
);

CREATE INDEX user_invitation_user ON user_invitation (user_id);
