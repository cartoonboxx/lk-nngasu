import { test, expect } from '@playwright/test'

for (const width of [375, 1440]) {
  test(`period picker selects a week only after applying (${width}px)`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.clock.install({ time: new Date('2026-10-23T10:00:00') })
    await page.goto('/schedule')
    const trigger = page.locator('main button[class*=trigger]:visible')
    const picker = page.getByRole('dialog')
    const weekLabel = page.locator('main').getByText('19 – 24 октября 2026 г.', { exact: true })
    await trigger.click()
    await expect(trigger).toHaveClass(/active/)
    await expect(picker).toBeVisible()
    await expect(picker.locator('td[class*=range]')).toHaveCount(7)
    await expect(picker.getByRole('button', { name: '19', exact: true })).toBeFocused()
    await picker.getByRole('button', { name: '5', exact: true }).click()
    await expect(weekLabel).toBeVisible()
    await picker.getByRole('button', { name: 'Отменить', exact: true }).click()
    await expect(picker).toBeHidden()
    await expect(trigger).not.toHaveClass(/active/)
    await expect(trigger).toBeFocused()
    await expect(weekLabel).toBeVisible()
    await trigger.click()
    await expect(picker.getByRole('button', { name: '19', exact: true })).toHaveClass(/selectedDay/)
    await picker.getByRole('button', { name: '5', exact: true }).click()
    await picker.getByRole('button', { name: 'Применить', exact: true }).click()
    await expect(picker).toBeHidden()
    await expect(
      page.locator('main').getByText('5 – 10 октября 2026 г.', { exact: true }),
    ).toBeVisible()
    await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
    await trigger.click()
    await picker.getByRole('button', { name: 'Сегодня', exact: true }).click()
    await picker.getByRole('button', { name: 'Применить', exact: true }).click()
    await expect(weekLabel).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
  })
}

test('calendar supports keyboard selection, year boundaries and Escape', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-23T10:00:00') })
  await page.goto('/schedule')
  const trigger = page.locator('main button[class*=trigger]:visible')
  await trigger.click()
  const picker = page.getByRole('dialog')
  await page.keyboard.press('ArrowDown')
  await expect(picker.getByRole('button', { name: '26', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await picker.getByRole('button', { name: 'Применить', exact: true }).click()
  await expect(
    page.getByRole('table').getByRole('columnheader', { name: 'Пн, 26 окт', exact: true }),
  ).toBeVisible()
  await trigger.click()
  for (let month = 0; month < 3; month++) {
    await picker.locator('[class*=monthNavigation] button').last().click()
  }
  await expect(picker.getByText('Январь 2027 г.', { exact: true })).toBeVisible()
  await picker.getByRole('button', { name: '1', exact: true }).click()
  await picker.getByRole('button', { name: 'Применить', exact: true }).click()
  await expect(
    page.locator('main').getByText('28 декабря – 2 января 2027 г.', { exact: true }),
  ).toBeVisible()
  await trigger.click()
  await picker.locator('[class*=monthNavigation] button').first().click()
  await page.keyboard.press('Escape')
  await expect(picker).toBeHidden()
  await expect(trigger).toBeFocused()
})

test('picker closes on outside click and adapts to viewport changes', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-23T10:00:00') })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/schedule')
  const trigger = page.locator('main button[class*=trigger]:visible')
  const picker = page.getByRole('dialog')
  await trigger.click()
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
  const popupBounds = await picker.boundingBox()
  const anchorBounds = await trigger.boundingBox()
  expect(popupBounds!.width).toBe(304)
  expect(popupBounds!.x).toBeGreaterThanOrEqual(anchorBounds!.x + anchorBounds!.width)
  expect(popupBounds!.x - anchorBounds!.x - anchorBounds!.width).toBeLessThan(16)
  expect(popupBounds!.y).toBeCloseTo(anchorBounds!.y, 0)
  await page.setViewportSize({ width: 1440, height: 400 })
  await expect(picker.locator(':scope > div')).toHaveCSS('height', '376px')
  await picker.getByRole('button', { name: 'Отменить', exact: true }).scrollIntoViewIfNeeded()
  await expect(picker.getByRole('button', { name: 'Отменить', exact: true })).toBeInViewport()
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.getByRole('heading', { name: 'Расписание', exact: true }).click()
  await expect(picker).toBeHidden()
  await trigger.click()
  await page.setViewportSize({ width: 320, height: 700 })
  await expect.poll(() => picker.evaluate((element) => element.matches(':modal'))).toBe(true)
  const sheetBounds = await picker.boundingBox()
  expect(Math.round(sheetBounds!.y + sheetBounds!.height)).toBe(700)
  await expect(page.locator('body')).toHaveCSS('overflow', 'hidden')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
  await page.mouse.click(10, 10)
  await expect(picker).toBeHidden()
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
  await trigger.click()
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect.poll(() => picker.evaluate((element) => element.matches(':modal'))).toBe(false)
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
  await page.keyboard.press('Escape')
  await expect(picker).toBeHidden()
})

test('mobile calendar uses the shared sheet and swipe cancels the draft selection', async ({
  page,
}) => {
  await page.setViewportSize({ width: 375, height: 900 })
  await page.clock.install({ time: new Date('2026-10-23T10:00:00') })
  await page.goto('/schedule')
  const trigger = page.locator('main button[class*=trigger]:visible')
  const picker = page.getByRole('dialog')
  await trigger.click()
  const handle = picker.locator('[class*=handle]')
  const panel = picker.locator(':scope > div')
  await expect(handle).toBeVisible()
  await expect
    .poll(async () => {
      const bounds = (await panel.boundingBox())!
      return Math.round(bounds.y + bounds.height)
    })
    .toBe(900)
  await picker.getByRole('button', { name: '5', exact: true }).click()
  const grip = (await handle.boundingBox())!
  await page.mouse.move(grip.x + grip.width / 2, grip.y + grip.height / 2)
  await page.mouse.down()
  await page.mouse.move(grip.x + grip.width / 2, 890, { steps: 16 })
  await page.mouse.up()
  await expect(picker).toBeHidden()
  await expect(trigger).not.toHaveClass(/active/)
  await expect(trigger).toBeFocused()
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
  await expect(
    page.locator('main').getByText('19 – 24 октября 2026 г.', { exact: true }),
  ).toBeVisible()
  await trigger.click()
  await expect(picker.getByRole('button', { name: '19', exact: true })).toHaveClass(/selectedDay/)
})
