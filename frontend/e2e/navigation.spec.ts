import { test, expect } from '@playwright/test'

test('mobile menu supports navigation, focus, and dismissal', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 667 })
  await page.goto('/dashboard')
  const menu = page.getByRole('button', { name: 'Ещё', exact: true })
  const navigation = page
    .locator('section')
    .filter({ has: page.getByRole('heading', { name: 'Ещё', exact: true }) })
  await expect(navigation).toBeHidden()
  await expect(page.locator('main')).toHaveCSS('margin-left', '0px')

  await menu.click()
  const close = navigation.locator('button').first()
  await expect(close).toBeFocused()
  await expect(page.locator('body')).toHaveCSS('overflow', 'hidden')
  await page.keyboard.press('Shift+Tab')
  await expect(navigation.locator('button').last()).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toBeFocused()
  await expect(navigation).toBeHidden()

  await page.locator('nav').last().getByRole('link', { name: 'Расписание' }).click()
  await expect(page).toHaveURL(/\/schedule$/)
  await menu.click()
  await navigation.getByRole('button', { name: 'Сообщения' }).click()
  await expect(page).toHaveURL(/\/messages$/)
  await expect(menu).toHaveClass(/active/)
  await expect(navigation).toBeHidden()
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
  await expect(page.locator('main')).not.toHaveAttribute('inert')

  await menu.click()
  await page.mouse.click(365, 40)
  await expect(navigation).toBeHidden()
})

test('desktop collapse state survives switching to mobile', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/dashboard')
  const main = page.locator('main')
  await page.locator('nav').first().locator('button').first().click()
  await expect(main).toHaveCSS('margin-left', '80px')
  await page.setViewportSize({ width: 320, height: 568 })
  await page.getByRole('button', { name: 'Ещё', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Ресурсы и сервисы' })).toBeVisible()
  await page.setViewportSize({ width: 1280, height: 800 })
  await expect(main).toHaveCSS('margin-left', '80px')
  await expect(main).not.toHaveAttribute('inert')
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
  await page.locator('nav').first().locator('button').first().click()
  await expect(main).toHaveCSS('margin-left', '280px')
})

test('mobile tabs fit narrow screens and keep courses active', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await page.goto('/subjects/1')
  const navigation = page.locator('nav').last()
  await expect(navigation.getByRole('link', { name: 'Предметы' })).toHaveClass(/active/)
  await expect(navigation.getByRole('link')).toHaveCount(3)
  const bounds = await navigation.boundingBox()
  expect(bounds?.width).toBe(320)
  expect(bounds?.y).toBeGreaterThan(480)
  await expect(page.getByRole('button', { name: 'Открыть меню' })).toHaveCount(0)
  await navigation.getByRole('link', { name: 'Главная' }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
})
